package com.searchhh.app.data.remote

import com.searchhh.app.data.remote.dto.CategoriesResponseDto
import com.searchhh.app.data.remote.dto.EntryDto
import com.searchhh.app.data.remote.dto.FeedbackRequestDto
import com.searchhh.app.data.remote.dto.FeedbackResponseDto
import com.searchhh.app.data.remote.dto.FundingMatchRequestDto
import com.searchhh.app.data.remote.dto.FundingMatchResponseDto
import com.searchhh.app.data.remote.dto.HealthDto
import com.searchhh.app.data.remote.dto.InsightRequestDto
import com.searchhh.app.data.remote.dto.InsightResponseDto
import com.searchhh.app.data.remote.dto.SearchResponseDto
import com.searchhh.app.data.remote.dto.SuggestResponseDto
import com.searchhh.app.data.remote.dto.TokenRequestDto
import com.searchhh.app.data.remote.dto.TokenResponseDto
import retrofit2.http.Body
import retrofit2.http.GET
import retrofit2.http.POST
import retrofit2.http.Path
import retrofit2.http.Query

/**
 * Retrofit contract for the SEARCHHH API (endpoints live in
 * backend/app/api/routes/, mirrored 1:1 by the FastAPI routers).
 * Blocks JSON is generated by kotlinx.serialization - no reflection, no Gson.
 */
interface SearchApi {

    @GET("api/v1/search")
    suspend fun search(
        @Query("q") query: String,
        @Query("limit") limit: Int = 20,
        @Query("offset") offset: Int = 0,
        @Query("category") category: String? = null,
        @Query("sort") sort: String = "relevance",
    ): SearchResponseDto

    @GET("api/v1/search/suggest")
    suspend fun suggest(
        @Query("q") query: String,
        @Query("limit") limit: Int = 5,
    ): SuggestResponseDto

    @GET("api/v1/search/categories")
    suspend fun categories(): CategoriesResponseDto

    @GET("api/v1/search/{id}")
    suspend fun entry(@Path("id") id: String): EntryDto

    @POST("api/v1/insights")
    suspend fun insight(@Body body: InsightRequestDto): InsightResponseDto

    @POST("api/v1/feedback")
    suspend fun feedback(@Body body: FeedbackRequestDto): FeedbackResponseDto

    @POST("api/v1/funding/match")
    suspend fun fundingMatch(@Body body: FundingMatchRequestDto): FundingMatchResponseDto

    @GET("health")
    suspend fun health(): HealthDto

    @POST("api/v1/auth/token")
    suspend fun token(@Body body: TokenRequestDto = TokenRequestDto()): TokenResponseDto
}
