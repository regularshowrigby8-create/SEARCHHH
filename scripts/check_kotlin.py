#!/usr/bin/env python3
"""Static sanity checks for the Kotlin sources - runs without a JVM.

This exists because the Android build only fails *after* Gradle has downloaded
half the internet, and because one class of error is invisible to the eye:

    Kotlin block comments NEST. A `/*` inside a KDoc block (for example the
    path `backend/app/api/routes/*`) opens a second comment, so the closing
    `*/` only terminates the inner one and the file ends "Unclosed comment".

Checks
  1. comment/string state machine per file (nested block comments, raw strings,
     escapes, char literals) - reports unterminated comments/strings
  2. brace / paren / bracket balance outside strings and comments
  3. `import com.searchhh.*` targets actually exist on disk
  3b. every `by` delegate has its getValue/setValue imports (Compose State)
  3c. every `when` over the sealed ApiResult has all three branches
  4. no stray `*/` or `/*` inside string literals
  5. TODO/FIXME budget, and no `System.out`/`printStackTrace`

Exit code 1 when any hard check fails.

Usage:
    python scripts/check_kotlin.py           # check android/ + report
    python scripts/check_kotlin.py --strict  # also fail on warnings
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_ROOTS = [ROOT / "android/app/src"]
PACKAGE_PREFIX = "com.searchhh."
# Generated by the Android Gradle plugin - no source file exists for these.
GENERATED_SYMBOLS = {"BuildConfig", "R"}

COMMENT_BUDGET = 25
BANNED_PATTERNS = {
    r"\bSystem\.out\.print": "use Timber instead of System.out",
    r"\bprintStackTrace\s*\(": "use Timber.e(throwable, ...) instead",
    r"\bThread\.sleep\s*\(": "use delay() / withContext(Dispatchers.IO)",
    r"\bGlobalScope\b": "use viewModelScope / applicationScope",
}


@dataclass
class Issue:
    path: Path
    line: int
    message: str
    hard: bool = True


@dataclass
class Result:
    issues: list[Issue] = field(default_factory=list)
    files: int = 0
    todos: int = 0

    def add(self, path: Path, line: int, message: str, hard: bool = True) -> None:
        self.issues.append(Issue(path, line, message, hard))

    @property
    def errors(self) -> list[Issue]:
        return [i for i in self.issues if i.hard]

    @property
    def warnings(self) -> list[Issue]:
        return [i for i in self.issues if not i.hard]


def line_of(text: str, index: int) -> int:
    return text.count("\n", 0, index) + 1


def scan_file(path: Path, result: Result) -> None:
    text = path.read_text(encoding="utf-8")
    n = len(text)
    i = 0
    stack: list[tuple[str, int]] = []  # open delimiters: (char, index)
    pairs = {")": "(", "]": "[", "}": "{"}
    while i < n:
        c = text[i]
        nxt = text[i + 1] if i + 1 < n else ""

        # --- comments -----------------------------------------------------
        if c == "/" and nxt == "/":
            end = text.find("\n", i)
            i = n if end == -1 else end
            continue

        if c == "/" and nxt == "*":
            # Kotlin block comments nest; walk to the matching close.
            depth = 1
            j = i + 2
            while j < n and depth > 0:
                if text.startswith("/*", j):
                    depth += 1
                    j += 2
                elif text.startswith("*/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            if depth > 0:
                result.add(path, line_of(text, i), "unterminated block comment (nested /* never closed)")
                return
            i = j
            continue

        # --- raw strings --------------------------------------------------
        if text.startswith('"""', i):
            j = i + 3
            while j < n and not text.startswith('"""', j):
                j += 2 if text[j] == "\\" else 1
            if j >= n:
                result.add(path, line_of(text, i), "unterminated raw string")
                return
            i = j + 3
            continue

        # --- char / string literals ---------------------------------------
        if c == '"':
            j = i + 1
            while j < n:
                if text[j] == "\\":
                    j += 2
                    continue
                if text[j] == "\n":
                    result.add(path, line_of(text, i), "unterminated string literal")
                    return
                if text[j] == '"':
                    break
                j += 1
            body = text[i + 1 : j]
            if "*/" in body:
                result.add(path, line_of(text, i), "`*/` inside a string literal - will be read as a comment end")
            i = j + 1
            continue

        if c == "'":
            # char literal vs. generic quote; only treat 'x' / '\n' as literals
            m = re.match(r"'(\\.|[^'\\\n])'", text[i:])
            if m:
                i += m.end()
                continue
            i += 1
            continue

        # --- brackets -----------------------------------------------------
        if c in "([{":
            stack.append((c, i))
        elif c in ")]}":
            if not stack:
                result.add(path, line_of(text, i), f"unmatched closing '{c}'")
            else:
                opener, index = stack.pop()
                if opener != pairs[c]:
                    result.add(
                        path,
                        line_of(text, i),
                        f"'{opener}' opened on line {line_of(text, index)} closed by '{c}'",
                    )
        i += 1

    for opener, index in stack:
        result.add(path, line_of(text, index), f"unclosed '{opener}'")

    # --- style / safety ------------------------------------------------
    for pattern, advice in BANNED_PATTERNS.items():
        for match in re.finditer(pattern, text):
            result.add(path, line_of(text, match.start()), advice, hard=False)

    result.todos += len(re.findall(r"\b(TODO|FIXME)\b", text))


DELEGATE_PATTERNS = (
    "collectAsStateWithLifecycle(",
    "collectAsState(",
    "remember {",
    "remember(",
    "rememberSaveable",
    "mutableStateOf(",
    "mutableIntStateOf(",
    "mutableFloatStateOf(",
    "mutableStateListOf(",
    "derivedStateOf",
    "viewModel(",
)

# `val x by ...` needs getValue; `var x by ...` needs getValue + setValue.
# Omitting them produces: "Type 'State<T>' has no method 'getValue(...)'".
IMPORT_GETVALUE = "import androidx.compose.runtime.getValue"
IMPORT_SETVALUE = "import androidx.compose.runtime.setValue"


def check_delegates(path: Path, result: Result) -> None:
    text = path.read_text(encoding="utf-8")
    uses_delegate = any(pattern in text for pattern in DELEGATE_PATTERNS)
    if not uses_delegate:
        return
    if re.search(r"\b(val|var)\s+\w+\s+by\s+", text) and IMPORT_GETVALUE not in text:
        result.add(
            path,
            1,
            "delegated property (`by`) without `import androidx.compose.runtime.getValue`",
        )
    if re.search(r"\bvar\s+\w+\s+by\s+", text) and IMPORT_SETVALUE not in text:
        result.add(
            path,
            1,
            "`var … by` without `import androidx.compose.runtime.setValue`",
        )


def _block_after(text: str, start: int) -> tuple[str, int]:
    """Return the balanced `{...}` body of `when (...) { ... }` at `start`.

    The subject of `when` may itself contain braces (`apiCall { ... }`), so we
    first skip to the matching `)` of the `when (` and only then look for `{`.
    """
    paren_at = text.find("(", start)
    if paren_at == -1:
        return "", start
    depth = 0
    i = paren_at
    while i < len(text):
        if text[i] == "(":
            depth += 1
        elif text[i] == ")":
            depth -= 1
            if depth == 0:
                break
        i += 1
    open_at = text.find("{", i)
    if open_at == -1:
        return "", start
    depth = 0
    i = open_at
    while i < len(text):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[open_at : i + 1], i
        i += 1
    return text[open_at:], len(text)


def check_when_exhaustive(path: Path, result: Result) -> None:
    """A `when` over ApiResult must handle Success, Failure and Loading.

    ApiResult is a sealed interface; a missing branch is a hard compile error
    ("'when' expression must be exhaustive"), and the compiler reports only one
    at a time, so catching them all up front saves build cycles.
    """
    text = path.read_text(encoding="utf-8")
    for match in re.finditer(r"\bwhen\s*\(", text):
        body, _ = _block_after(text, match.start())
        if "ApiResult.Success" not in body:
            continue
        missing = [
            branch
            for branch, marker in (
                ("Failure", "ApiResult.Failure"),
                ("Loading", "ApiResult.Loading"),
            )
            if marker not in body
        ]
        if missing and "else ->" not in body:
            result.add(
                path,
                line_of(text, match.start()),
                f"`when` over ApiResult is not exhaustive - missing: {', '.join(missing)}",
            )


def check_imports(path: Path, result: Result) -> None:
    """Every `import com.searchhh.x.Y` must resolve to a file in the sources."""
    text = path.read_text(encoding="utf-8")
    known = {".kt"}
    src = path.parent
    roots = [r for r in SOURCE_ROOTS if r.exists()]
    for match in re.finditer(r"^import (com\.searchhh\.[\w.]+)", text, re.MULTILINE):
        fqcn = match.group(1)
        tail = fqcn[len(PACKAGE_PREFIX) :]
        parts = tail.split(".")
        candidates = [
            # class file: .../x/Y.kt  (package part = path)
            "/".join(parts) + ".kt",
            # top-level symbol in a file with a different name
            "/".join(parts[:-1]) + ".kt",
        ]
        found = False
        for root in roots:
            for candidate in candidates:
                if (root / "kotlin" / "com/searchhh" / candidate).exists():
                    found = True
                    break
            if found:
                break
        if not found:
            # Fall back to a plain symbol search: top-level functions, extension
            # properties (`val Context.x by ...`) and generics defeat declaration regexes.
            symbol = parts[-1]
            if re.search(rf"\b{re.escape(symbol)}\b", _all_sources_text()):
                found = True
        if not found:
            result.add(path, line_of(text, match.start()), f"import target not found: {fqcn}", hard=False)

    del known


_ALL_TEXT: str | None = None


def _all_sources_text() -> str:
    global _ALL_TEXT
    if _ALL_TEXT is None:
        _ALL_TEXT = "\n".join(
            p.read_text(encoding="utf-8") for root in SOURCE_ROOTS if root.exists() for p in root.rglob("*.kt")
        )
    return _ALL_TEXT


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--strict", action="store_true", help="treat warnings as failures")
    args = parser.parse_args()

    result = Result()
    for root in SOURCE_ROOTS:
        for path in sorted(root.rglob("*.kt")):
            result.files += 1
            scan_file(path, result)
            check_imports(path, result)
            check_delegates(path, result)
            check_when_exhaustive(path, result)

    for issue in result.errors:
        print(f"ERROR  {issue.path.relative_to(ROOT)}:{issue.line}: {issue.message}")
    for issue in result.warnings:
        print(f"WARN   {issue.path.relative_to(ROOT)}:{issue.line}: {issue.message}")

    print(
        f"\n{result.files} Kotlin files | {len(result.errors)} errors | "
        f"{len(result.warnings)} warnings | {result.todos} TODO/FIXME"
    )

    failed = bool(result.errors) or (args.strict and bool(result.warnings))
    if result.todos > COMMENT_BUDGET:
        print(f"note: {result.todos} TODO/FIXME markers (budget {COMMENT_BUDGET})")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
